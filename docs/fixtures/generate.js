#!/usr/bin/env node
/*
 * Regenerate the fixtures the tool produces (ROADMAP N160, N167, N169).
 *
 * Both files are produced by the tool rather than written by hand, so they are exactly what `docs/`
 * emits, and a test fails when the two drift: the app's JVM test decodes them, and the page's own test
 * rebuilds the program document from its sheet and compares. Run it after changing anything that
 * affects either output:
 *
 *     node docs/fixtures/generate.js
 *
 * The data is invented: no real export is ever committed, and `.gitignore` keeps `Gym-*.json` out of
 * the repository for that reason.
 */
'use strict';

var path = require('path');
var fs = require('fs');
var vm = require('vm');
var api = require(path.join(__dirname, '..', 'app.js'));

/* ------------------------------------------------------------------ *
 * The synthetic backup (N160)
 * ------------------------------------------------------------------ */

/* Two sessions, three exercises, a warm-up, a pound row and an RPE half-point. */
var ROWS = [
  { date: '2024-03-04', exercise: 'Back Squat', reps: 10, weight: 40, unit: 'kg', type: 'W' },
  { exercise: 'Back Squat', reps: 5, weight: 100, unit: 'kg', rpe: 8, type: 'N' },
  { exercise: 'Back Squat', reps: 5, weight: 100, unit: 'kg', rpe: 8.5, type: 'N' },
  { exercise: 'Standing Calf Raise', reps: 12, weight: 150, unit: 'lb', rpe: 9, type: 'N' },
  { date: '2024-03-06', exercise: 'Bench Press', reps: 5, weight: 80, unit: 'kg', rpe: 9, type: 'N' },
  { exercise: 'Bench Press', reps: 5, weight: 80, unit: 'kg', type: 'N' }
];

var model = api.buildModel(ROWS, {
  seed: 'import-helper-fixture',
  sheet: 'fixture',
  dateOrder: 'dmy'
});

var result = api.buildExport(model, { exportedAt: 1709683200000 });
if (!result.ok) {
  console.error('the tool refused the backup fixture:');
  result.problems.forEach(function (problem) {
    console.error('  ' + problem.path + ': ' + problem.message);
  });
  process.exit(1);
}

var backupTarget = path.join(__dirname, 'import-helper-backup.json');
fs.writeFileSync(backupTarget, api.serializeExport(result.file));
console.log(
  'wrote ' + path.relative(process.cwd(), backupTarget) +
  ': ' + result.file.sessions.length + ' sessions, ' +
  result.file.sessionExercises.length + ' exercises, ' +
  result.file.sets.length + ' sets'
);

/* ------------------------------------------------------------------ *
 * The program document (N167, N169)
 * ------------------------------------------------------------------ */

/* The sheet the page's test builds from, so the input and the expected document travel together. */
var PROGRAM_SHEET = [
  ['Program', 'Day', 'Weekday', 'Exercise', 'Sets', 'Reps', 'Load', 'Rest', 'RPE', 'Note'].join('\t'),
  ['Autumn block', 'Upper A', 'Mon', 'Competition Bench Press', '5', '3', '82.5', '180', '8', 'pause 1s'].join('\t'),
  ['Autumn block', 'Upper A', 'Mon', 'Barbell Row', '4', '6-8', '70', '120', '8', ''].join('\t'),
  ['Autumn block', 'Upper A', 'Wed', 'Competition Bench Press', '5', '3', '82.5', '180', '8', ''].join('\t'),
  ['Autumn block', 'Lower A', 'Fri', 'Back Squat', '5', '5', '100', '240', '8', 'belts on'].join('\t'),
  ['Autumn block', 'Lower A', 'Fri', 'Machine Curl Call', '3', '10', '30', '90', '8', ''].join('\t')
].join('\n');
var PROGRAM_EXPORTED_AT = 1790000000000;

/* The app's seeded library, so a seeded name keeps its slug instead of being created as a new movement. */
var seedSandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'seed-catalog.js'), 'utf8'), seedSandbox);
var seededExercises = seedSandbox.window.SEEDED_EXERCISES;

var parsedSheet = api.parseProgramSheet(PROGRAM_SHEET);
var program = api.buildProgramDocument(parsedSheet, {
  exportedAt: PROGRAM_EXPORTED_AT,
  exercises: seededExercises
});
if (!program.ok) {
  console.error('the tool refused the program sheet:');
  program.problems.forEach(function (problem) {
    console.error('  ' + problem.message);
  });
  process.exit(1);
}

var programTarget = path.join(__dirname, 'program-document.js');
fs.writeFileSync(
  programTarget,
  '/* The program sheet and the document it must write (N167, N169).\n' +
  ' *\n' +
  ' * GENERATED by docs/fixtures/generate.js — do not edit. The page\'s test parses window.PROGRAM_SHEET_TEXT\n' +
  ' * and compares the document it builds with window.PROGRAM_DOCUMENT_FIXTURE; ProgramDocumentFixtureTest\n' +
  ' * decodes the same object with the app\'s codec. Regenerate with:\n' +
  ' *\n' +
  ' *     node docs/fixtures/generate.js\n' +
  ' */\n' +
  'window.PROGRAM_SHEET_TEXT = ' + JSON.stringify(PROGRAM_SHEET) + ';\n' +
  'window.PROGRAM_DOCUMENT_FIXTURE = ' + JSON.stringify(program.document, null, 2) + ';\n'
);
console.log(
  'wrote ' + path.relative(process.cwd(), programTarget) +
  ': ' + program.stats.days + ' days, ' +
  program.stats.exercises + ' exercise rows, ' +
  program.stats.sets + ' sets'
);
